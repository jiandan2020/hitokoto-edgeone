// 将仓库中的语录内联到 EdgeOne Pages 函数，避免运行时依赖外部存储。
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(root, "functions", "index.js"), "utf8");
const sentences = Object.fromEntries("abcdefghijkl".split("").map(category => [
    category,
    JSON.parse(readFileSync(join(root, "sentences", `${category}.json`), "utf8")),
]));
const start = source.indexOf("// 通用响应标头");
if (start < 0 || !source.includes("export async function onRequest(context)")) {
    throw new Error("原始函数格式已改变，无法生成 EdgeOne Pages 函数");
}
const handler = source.slice(start).replace(
    "export async function onRequest(context)",
    "export default async function onRequest(context)",
);
const output = `// Generated by node build.js; do not edit.\nconst sentencesMap = ${JSON.stringify(sentences)};\n\n${handler}`;
mkdirSync(join(root, "edge-functions"), { recursive: true });
writeFileSync(join(root, "edge-functions", "api.js"), output);
console.log(`Generated edge-functions/api.js (${Buffer.byteLength(output)} bytes)`);
