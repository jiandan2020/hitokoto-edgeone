// 构建句子长度索引；句子正文由同一部署的静态数据提供。
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(root, "functions", "index.js"), "utf8");
const index = {};
const hashes = {};
const hash = createHash("sha256");
for (const category of "abcdefghijkl") {
    const bytes = readFileSync(join(root, "sentences", `${category}.json`));
    hashes[category] = createHash("sha256").update(bytes).digest("hex");
    hash.update(category).update(bytes);
    const records = JSON.parse(bytes.toString("utf8"));
    index[category] = {};
    records.forEach((record, i) => {
        (index[category][record.length] ||= []).push(i);
    });
}
const start = source.indexOf("// 通用响应标头");
if (start < 0 || !source.includes("export async function onRequest(context)")) {
    throw new Error("原始函数格式已改变，无法生成 EdgeOne Pages 函数");
}
const handler = source.slice(start).replace(
    "export async function onRequest(context)",
    "export default async function onRequest(context)",
);
const version = hash.digest("hex");
// 把完整索引与每类内容摘要内联进 api.js：冷启动不用再取一次
// sentence-index.json，只剩一次分类文件取数；取到的分类文件先按摘要
// 校验，通过才进缓存与 KV，摘要与版本不符的旧数据进不了缓存。
const output = `// Generated by node build.js; do not edit.\nconst sentenceVersion = ${JSON.stringify(version)};\nconst embeddedSentenceIndex = ${JSON.stringify(index)};\nconst embeddedSentenceHashes = ${JSON.stringify(hashes)};\n\n${handler}`;
mkdirSync(join(root, "edge-functions"), { recursive: true });
writeFileSync(join(root, "sentence-index.json"), JSON.stringify({ version, index, hashes }));
writeFileSync(join(root, "edge-functions", "api.js"), output);
console.log(`Generated sentence-index.json and edge-functions/api.js (${Buffer.byteLength(output)} bytes)`);
