// 打包脚本（v5.1 第 3 期）：把 api-core/handler.js 打包成单文件 Edge Function，
// 前面缀上版本 / 索引 / 摘要常量。供 build.js（写文件）与
// check-deployment.js（内存比对）共用；本文件不写任何文件。
import { build } from "esbuild";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

export async function buildApiBundle({ version, index, hashes }) {
    const banner = `// Generated by node build.js; do not edit.\nconst sentenceVersion = ${JSON.stringify(version)};\nconst embeddedSentenceIndex = ${JSON.stringify(index)};\nconst embeddedSentenceHashes = ${JSON.stringify(hashes)};\n\n`;
    const result = await build({
        entryPoints: [join(root, "api-core", "handler.js")],
        bundle: true,
        format: "esm",
        platform: "neutral",
        banner: { js: banner },
        write: false,
    });
    return result.outputFiles[0].text;
}
