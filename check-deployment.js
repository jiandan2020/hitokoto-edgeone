// 仅读取并校验仓库中的部署产物，不生成或修改文件。
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { validateCategoryRecords } from "./scripts/validate-corpus.mjs";

const read = path => readFileSync(new URL(path, import.meta.url), "utf8");
const { version, index, hashes } = JSON.parse(read("./sentence-index.json"));
const hash = createHash("sha256");
const seenIds = new Set();
for (const key of "abcdefghijkl") {
    const bytes = readFileSync(new URL(`./sentences/${key}.json`, import.meta.url));
    hash.update(key).update(bytes);
    if (!hashes || createHash("sha256").update(bytes).digest("hex") !== hashes[key]) {throw new Error(`句子库分类 ${key} 的内容摘要不一致`);}
    const records = JSON.parse(bytes.toString("utf8"));
    validateCategoryRecords(key, records, seenIds);
    const buckets = index?.[key];
    if (!buckets || typeof buckets !== "object") {throw new Error(`缺少索引分类 ${key}`);}
    const seen = new Set();
    for (const [length, positions] of Object.entries(buckets)) {
        if (!Array.isArray(positions)) {throw new Error(`索引分类 ${key} 格式错误`);}
        for (const position of positions) {
            const record = records[position];
            if (!Number.isInteger(position) || seen.has(position) || !record || record.type !== key || String(record.length) !== length) {
                throw new Error(`索引分类 ${key} 与句子库不一致`);
            }
            seen.add(position);
        }
    }
    if (seen.size !== records.length) {throw new Error(`索引分类 ${key} 不完整`);}
}
if (hash.digest("hex") !== version) {throw new Error("索引与句子库版本不一致");}
const source = read("./functions/index.js");
const start = source.indexOf("// 通用响应标头");
const signature = "export async function onRequest(context)";
if (start < 0 || !source.includes(signature)) {throw new Error("原始函数格式错误");}
const expected = `// Generated by node build.js; do not edit.\nconst sentenceVersion = ${JSON.stringify(version)};\nconst embeddedSentenceIndex = ${JSON.stringify(index)};\nconst embeddedSentenceHashes = ${JSON.stringify(hashes)};\n\n${source.slice(start).replace(signature, "export default async function onRequest(context)")}`;
if (read("./edge-functions/api.js") !== expected) {throw new Error("边缘函数与源代码或索引版本不一致");}
console.log("部署文件校验通过，未生成任何文件。");
